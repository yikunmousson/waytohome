const assert=require('node:assert/strict');
const M=require('../web/manual-model.js');
const now=Date.parse('2026-09-29T12:00:00+08:00');
const row=(x={})=>({id:'a',direction:'outbound',corridor:'leguang',depart:'2026-09-30T22:00',queried:'2026-09-29T11:00',duration:360,source:'地图 App',roads:'广连—许广',note:'',tolls:null,updated_at:'2026-09-29T03:00:00Z',...x});
assert.throws(()=>M.time('2026-02-30T00:00'));
assert.throws(()=>M.validate(row({duration:-1})));
assert.throws(()=>M.validate(row({tolls:'0'})));
assert.equal(M.validate(row()).tolls,null);
assert.throws(()=>M.parse(JSON.stringify({version:1,records:[row(),row()]})));
assert.equal(M.status(row({corridor:'unknown'}),now),'待核验');
assert.equal(M.status(row({queried:'2026-09-28T10:00'}),now),'需重新查询');
assert.equal(M.status(row({queried:'2026-09-29T13:00'}),now),'查询时间在未来');
assert.equal(M.status(row({depart:'2026-09-28T10:00'}),now),'非出发前预测');
const newer=row({id:'b',queried:'2026-09-29T11:30',duration:390});
assert.deepEqual(M.compare([row(),newer],{direction:'outbound',now}).map(r=>r.id),['b']);
assert.equal(M.compare([row()],{direction:'return',now}).length,0);
assert.equal(M.compare([row()],{direction:'outbound',now,rest:60,arrival:'2026-10-01T04:30'}).length,0);
assert.equal(M.compare([row()],{direction:'outbound',now,rest:0,arrival:'2026-10-01T04:30'}).length,1);
assert.equal(M.merge([row()],[row({duration:400})],false)[0].duration,360);
assert.equal(M.merge([row()],[row({duration:400})],true)[0].duration,400);
assert.deepEqual(M.parse(JSON.stringify({version:1,records:[row()]})),[row()]);
console.log('✓ 手动记录校验、时间、版本、合并、筛选与跨日抵达测试通过');
